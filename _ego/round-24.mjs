const task = await taskSpace(1)
const page = task.page("p1")
await page.goto("https://www.oiioii.ai/zh/price", { waitUntil: "networkidle", timeout: 60000 }).catch(() => {})
await new Promise(r => setTimeout(r, 6000))
const rows = await page.evaluate(() => {
  const tb = document.querySelector("table")
  return [...tb.querySelectorAll("tr")].map(tr => [...tr.querySelectorAll("th,td")].map(td => (td.innerText || "").replace(/\s+/g, " ").trim()))
})
console.log("总行", rows.length)
rows.slice(44).forEach((r, i) => console.log((i + 44) + ": " + r.join(" | ")))
